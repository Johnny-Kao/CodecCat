"""Freeze original-byte windows from Vim source-controlled PO translation catalogs.

No model import, fitting or scoring. The raw translations, which Vim ships
as encoded .po files, are not redistributed. Some catalogs are generated by
the Vim build system from source translations: they remain real deployed
repository bytes but are NOT proof of historically native authored encoding.
"""
from __future__ import annotations
import argparse,codecs,collections,hashlib,json,pathlib,re,subprocess

VIM_REV="cbe1cf017d9027c8e34599333ef69d7e20e1bf8d"
WINDOW=2048
POSITIONS=(0.08,0.30,0.58,0.83)
MIN_NONASCII=12
HEADER=re.compile(rb'Content-Type:\s*text/plain;\s*charset=([A-Za-z0-9_.-]+)',re.I)
SNIPPET_SCHEME="strict 2048-byte substring of native .po translation bytes, plus original bytes only"

def sha(blob):
    return hashlib.sha256(blob).hexdigest()

def fragments(raw):
    """Collect only msgstr value lines, stripping PO syntactic outer quotes.

    This is a stable raw-byte extraction, not a Unicode decode or re-encode.
    The GNU PO escape bytes are left unchanged. Metadata/msgid/comment lines
    are deliberately not sent to detectors.
    """
    chunks=[]
    inside=False
    for line in raw.splitlines():
        if line.startswith(b"msgstr ") or re.match(rb'msgstr\[\d+\] ',line):
            inside=True
            at=line.find(b'"')
            if at>=0 and line.endswith(b'"') and len(line)>at+1:
                chunks.append(line[at+1:-1])
        elif inside and line.startswith(b'"') and line.endswith(b'"'):
            chunks.append(line[1:-1])
        elif line.startswith((b"msgid",b"msgctxt",b"msgstr")) or not line:
            inside=False
    return b"\n".join(chunks)

def take_window(data,start,codec):
    end=min(len(data),start+WINDOW)
    # Do not repair underlying bytes, merely shift boundary to preserve full
    # encoded code units. Same bytes, no fallback replacement/recoding.
    for shift_left in range(5):
        for shift_right in range(5):
            a=start+shift_left;b=end-shift_right
            if a>=b or b-a<512: continue
            piece=data[a:b]
            if sum(x>=128 for x in piece)<MIN_NONASCII:continue
            try: piece.decode(codec,"strict")
            except (LookupError,UnicodeError):continue
            return piece
    return None

def catalog_samples(filename):
    raw=filename.read_bytes()
    match=HEADER.search(raw[:15000])
    if match is None:
        return [],{"path":filename.name,"reason":"no_usable_declared_charset"}
    claimed=match.group(1).decode("ascii")
    try: codec=codecs.lookup(claimed).name
    except LookupError:
        return [],{"path":filename.name,"reason":"unsupported_claimed_codec","claimed":claimed}
    payload=fragments(raw)
    if len(payload)<1024:
        return [],{"path":filename.name,"reason":"insufficient_nonmetadata_bytes","claimed":claimed}
    try: payload.decode(codec,"strict")
    except UnicodeError:
        return [],{"path":filename.name,"reason":"invalid_translation_content","claimed":claimed}
    selected=[]
    for i,rel in enumerate(POSITIONS):
        offset=round((len(payload)-WINDOW)*rel)
        sample=take_window(payload,max(0,offset),codec)
        if sample is None: continue
        selected.append({
            "file":filename.name,"window":i,"codec":codec,"declared":claimed,
            "nbytes":len(sample),"sha256":sha(sample),
            "decoded_sha256":sha(sample.decode(codec,"strict").encode("utf-8","surrogatepass")),
            "high_bit_bytes":sum(b>=128 for b in sample),
        })
    catalog={"path":filename.name,"declared":claimed,"codec":codec,
             "file_sha256":sha(raw),"source_bytes":len(raw),
             "translation_stream_bytes":len(payload),
             "windows":len(selected),
             "generated_by_build":b"Generated from " in raw[:1300]}
    return selected,catalog

def freeze(args):
    root=pathlib.Path(args.root).resolve()
    revision=subprocess.check_output(["git","-C",str(root),"rev-parse","HEAD"],text=True).strip()
    if revision!=VIM_REV:raise RuntimeError("Vim checkout revision mismatch")
    results=[];catalogs=[]
    for f in sorted((root/"src"/"po").glob("*.po")):
        rows,rec=catalog_samples(f)
        results.extend(rows);catalogs.append(rec)
    if len(results)<100:raise RuntimeError(f"too few strictly decoded real catalog windows: {len(results)}")
    collisions=collections.Counter(r["sha256"] for r in results)
    duplicate_windows=sum(v-1 for v in collisions.values() if v>1)
    manifest={
        "schema":"codeccat-vim-po-natural-byte-window-freeze-v1",
        "origin":"vim/vim at pinned revision", "source_revision":revision,
        "license":"Vim project license; TEST-ONLY, do not redistribute contents or train candidate",
        "sampling":SNIPPET_SCHEME,"window_bytes":WINDOW,"window_positions":POSITIONS,
        "min_high_bit_bytes":MIN_NONASCII,
        "data_caveats":[
            "Real source-controlled .po bytes; some are generated from original catalog translations.",
            "Translation payload excludes charset declarations and original English msgid blocks.",
            "Four windows per .po file are correlated; evaluate at file and language level, not i.i.d. rows.",
            "Derived quote/escape markup remains in extracted Unicode text.",
            "No assert about original naturally authored encoding of build-generated variants.",
        ],
        "catalogs":catalogs,
        "windows":results,
        "number_catalogs":len(catalogs),
        "supported_catalogs":sum(r.get("windows",0)>0 for r in catalogs),
        "number_windows":len(results),
        "duplicate_byte_windows":duplicate_windows,
    }
    manifest["fingerprint"]=sha(json.dumps(manifest,ensure_ascii=False,sort_keys=True).encode())
    out=pathlib.Path(args.out);out.mkdir(parents=True,exist_ok=True)
    (out/"source_manifest.json").write_text(json.dumps(manifest,indent=2,sort_keys=True,ensure_ascii=False)+"\n")
    print("VIM_SOURCE_FREEZE_BEGIN")
    print(json.dumps({"fingerprint":manifest["fingerprint"],"source_revision":revision,
                      "number_catalogs":len(catalogs),
                      "supported_catalogs":manifest["supported_catalogs"],
                      "number_windows":len(results),"duplicate_byte_windows":duplicate_windows,
                      "catalogs":catalogs},ensure_ascii=False,indent=2))
    print("VIM_SOURCE_FREEZE_END")

if __name__=="__main__":
    ap=argparse.ArgumentParser()
    ap.add_argument("--root",required=True)
    ap.add_argument("--out",default="research-results/vim-po-freeze")
    freeze(ap.parse_args())
